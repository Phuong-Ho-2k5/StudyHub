CREATE TABLE chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_chat_session_title CHECK (CHAR_LENGTH(TRIM(title)) BETWEEN 1 AND 150)
);
CREATE INDEX idx_chat_sessions_owner_course ON chat_sessions(user_id, course_id, updated_at, id);

CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_sessions(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    status VARCHAR(30),
    model VARCHAR(255),
    prompt_version VARCHAR(100),
    citations_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_chat_message_role CHECK (role IN ('USER', 'ASSISTANT')),
    CONSTRAINT chk_chat_message_status CHECK (status IN ('ANSWERED', 'INSUFFICIENT_CONTEXT')),
    CONSTRAINT chk_chat_message_metadata CHECK (
        (role = 'USER' AND status IS NULL AND model IS NULL AND prompt_version IS NULL)
        OR (role = 'ASSISTANT' AND status IS NOT NULL AND prompt_version IS NOT NULL)
    )
);
CREATE INDEX idx_chat_messages_session ON chat_messages(session_id, id);
