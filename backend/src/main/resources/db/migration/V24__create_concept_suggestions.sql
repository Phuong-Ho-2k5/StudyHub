CREATE TABLE concept_suggestion_batches (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    published_ingestion_id VARCHAR(36) NOT NULL,
    model VARCHAR(200) NOT NULL,
    prompt_version VARCHAR(100) NOT NULL,
    coverage_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_concept_batches_scope ON concept_suggestion_batches(user_id,course_id,document_id);

CREATE TABLE concept_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id VARCHAR(36) NOT NULL REFERENCES concept_suggestion_batches(id) ON DELETE CASCADE,
    ordinal INTEGER NOT NULL CHECK(ordinal >= 0),
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    citations_json TEXT NOT NULL,
    state VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(state IN ('PENDING','CONFIRMED')),
    concept_id BIGINT REFERENCES concepts(id) ON DELETE SET NULL,
    confirmed_name VARCHAR(150),
    confirmed_description VARCHAR(1000),
    confirmed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_concept_suggestion_ordinal UNIQUE(batch_id,ordinal),
    CONSTRAINT chk_concept_suggestion_confirmation CHECK (
        (state='PENDING' AND concept_id IS NULL AND confirmed_at IS NULL
            AND confirmed_name IS NULL AND confirmed_description IS NULL)
        OR (state='CONFIRMED' AND confirmed_at IS NOT NULL
            AND confirmed_name IS NOT NULL AND confirmed_description IS NOT NULL))
);
