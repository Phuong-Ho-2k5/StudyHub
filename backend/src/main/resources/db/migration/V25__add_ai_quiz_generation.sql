CREATE TABLE quiz_generations (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    request_key VARCHAR(100) NOT NULL,
    fingerprint VARCHAR(64) NOT NULL,
    quiz_id BIGINT UNIQUE REFERENCES quizzes(id) ON DELETE SET NULL,
    model VARCHAR(200) NOT NULL,
    prompt_version VARCHAR(100) NOT NULL,
    coverage_json TEXT NOT NULL,
    response_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_quiz_generation_request UNIQUE(user_id, request_key)
);

CREATE TABLE quiz_question_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation_id VARCHAR(36) NOT NULL REFERENCES quiz_generations(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    document_id BIGINT NOT NULL,
    ingestion_id VARCHAR(36) NOT NULL,
    chunk_id BIGINT NOT NULL,
    citation_json TEXT NOT NULL,
    CONSTRAINT uq_quiz_question_evidence UNIQUE(question_id, chunk_id)
);
CREATE INDEX idx_quiz_evidence_generation ON quiz_question_evidence(generation_id);
